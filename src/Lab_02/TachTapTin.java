    private void btnTachFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTachFileActionPerformed
        String pathNguon = txtFileNguon.getText().trim();
        if (pathNguon.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập hoặc chọn tập tin nguồn!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        File fileNguon = new File(pathNguon);
        if (!fileNguon.exists() || !fileNguon.isFile()) {
            JOptionPane.showMessageDialog(this, "Tập tin nguồn \"" + pathNguon + "\" không tồn tại hoặc không phải là file!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        danhSachCacMang.clear();

        // Đọc tập tin và tách thành từng đoạn, mỗi đoạn lưu vào mảng số nguyên tối đa 100 phần tử
        try (FileInputStream fis = new FileInputStream(fileNguon)) {
            byte[] buffer = new byte[100];
            int bytesRead;

            while ((bytesRead = fis.read(buffer)) != -1) {
                // Tạo mảng số nguyên có kích thước tương ứng (tối đa 100)
                int[] mangDoan = new int[bytesRead];
                for (int i = 0; i < bytesRead; i++) {
                    mangDoan[i] = buffer[i] & 0xFF; // Chuyển byte thành số nguyên (0..255)
                }
                danhSachCacMang.add(mangDoan);
            }

            // Hiển thị thông tin các mảng số nguyên lên txtKetQuaTach
            StringBuilder sb = new StringBuilder();
            sb.append("TẬP TIN NGUỒN: ").append(fileNguon.getName()).append("\n");
            sb.append("Kích thước file: ").append(fileNguon.length()).append(" bytes\n");
            sb.append("Tổng số đoạn mảng tách được: ").append(danhSachCacMang.size()).append(" mảng (mỗi mảng <= 100 phần tử)\n");
            sb.append("=========================================\n\n");

            for (int i = 0; i < danhSachCacMang.size(); i++) {
                int[] mang = danhSachCacMang.get(i);
                sb.append(String.format("--- ĐOẠN %d (Kích thước: %d số nguyên) ---\n", (i + 1), mang.length));
                sb.append(Arrays.toString(mang)).append("\n\n");
            }

            txtKetQuaTach.setText(sb.toString());
            txtNoiDungMangTxt.setText(""); // Xóa nội dung file đích cũ
            lblTrangThai.setText("Đã tách tập tin thành " + danhSachCacMang.size() + " đoạn mảng số nguyên trong bộ nhớ.");

            JOptionPane.showMessageDialog(this,
                    "Tách tập tin thành công!\nTổng cộng " + danhSachCacMang.size() + " mảng số nguyên (mỗi mảng <= 100 phần tử).",
                    "Thành công", JOptionPane.INFORMATION_MESSAGE);

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi đọc và tách tập tin: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnTachFileActionPerformed

    private void btnGhiFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGhiFileActionPerformed
        if (danhSachCacMang.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Chưa có dữ liệu mảng nào trong bộ nhớ!\nVui lòng bấm '1. Tách tập tin vào mảng' trước khi ghi.",
                    "Chưa tách tập tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String pathDich = txtFileDich.getText().trim();
        if (pathDich.isEmpty()) {
            pathDich = "Mang.txt";
            txtFileDich.setText(pathDich);
        }

        File fileDich = new File(pathDich);

        // Đọc nội dung các mảng và ghi vào tập tin Mang.txt
        try (BufferedWriter bw = new BufferedWriter(new FileWriter(fileDich))) {
            StringBuilder sbHienThi = new StringBuilder();

            bw.write("=== DANH SÁCH CÁC MẢNG SỐ NGUYÊN ĐƯỢC TÁCH TỪ TẬP TIN ===");
            bw.newLine();
            bw.write("Nguồn gốc: " + txtFileNguon.getText().trim());
            bw.newLine();
            bw.write("Tổng số đoạn mảng: " + danhSachCacMang.size());
            bw.newLine();
            bw.write("Kích thước tối đa mỗi mảng: 100 phần tử");
            bw.newLine();
            bw.write("==========================================================");
            bw.newLine();
            bw.newLine();

            sbHienThi.append("=== DANH SÁCH CÁC MẢNG SỐ NGUYÊN ĐƯỢC TÁCH TỪ TẬP TIN ===\n");
            sbHienThi.append("Nguồn gốc: ").append(txtFileNguon.getText().trim()).append("\n");
            sbHienThi.append("Tổng số đoạn mảng: ").append(danhSachCacMang.size()).append("\n");
            sbHienThi.append("Kích thước tối đa mỗi mảng: 100 phần tử\n");
            sbHienThi.append("==========================================================\n\n");

            for (int i = 0; i < danhSachCacMang.size(); i++) {
                int[] mang = danhSachCacMang.get(i);

                String tieuDe = String.format("--- MẢNG ĐOẠN %d (Kích thước: %d phần tử) ---", (i + 1), mang.length);
                bw.write(tieuDe);
                bw.newLine();
                sbHienThi.append(tieuDe).append("\n");

                // Ghi các phần tử của mảng
                StringBuilder sbPhanTu = new StringBuilder();
                for (int j = 0; j < mang.length; j++) {
                    sbPhanTu.append(mang[j]);
                    if (j < mang.length - 1) {
                        sbPhanTu.append(", ");
                    }
                    // Xuống dòng mỗi 20 số để file dễ nhìn
                    if ((j + 1) % 20 == 0 && j < mang.length - 1) {
                        sbPhanTu.append("\n");
                    }
                }

                bw.write(sbPhanTu.toString());
                bw.newLine();
                bw.newLine();

                sbHienThi.append(sbPhanTu.toString()).append("\n\n");
            }

            bw.flush();

            txtNoiDungMangTxt.setText(sbHienThi.toString());
            lblTrangThai.setText("Đã ghi thành công " + danhSachCacMang.size() + " đoạn mảng vào: " + fileDich.getName());

            JOptionPane.showMessageDialog(this,
                    "Đã ghi thành công nội dung các mảng vào tập tin:\n" + fileDich.getAbsolutePath(),
                    "Thành công", JOptionPane.INFORMATION_MESSAGE);

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Lỗi khi ghi vào tập tin: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnGhiFileActionPerformed

