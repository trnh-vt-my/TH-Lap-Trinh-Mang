    private void btnTaoVaLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTaoVaLuuActionPerformed
        int n;
        try {
            n = Integer.parseInt(txtSoLuong.getText().trim());
            if (n <= 0) {
                JOptionPane.showMessageDialog(this, "Số lượng phân số phải là số nguyên dương (> 0)!", "Lỗi nhập liệu", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập số lượng hợp lệ!", "Lỗi nhập liệu", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String fileName = txtTenFile.getText().trim();
        if (fileName.isEmpty()) {
            fileName = "phanso.dat";
            txtTenFile.setText(fileName);
        }

        // Tạo n đối tượng phân số ngẫu nhiên
        Random rand = new Random();
        ArrayList<PhanSo> danhSachPhanSo = new ArrayList<>();
        StringBuilder sbGoc = new StringBuilder();
        sbGoc.append(String.format("=== ĐÃ TẠO %d PHÂN SỐ NGẪU NHIÊN ===\n", n));

        for (int i = 1; i <= n; i++) {
            // Tử số ngẫu nhiên từ 1 đến 50
            int tu = rand.nextInt(50) + 1;
            // Mẫu số ngẫu nhiên từ 2 đến 50 (để mẫu số khác 0 và xuất hiện nhiều số nguyên tố)
            int mau = rand.nextInt(49) + 2;

            PhanSo ps = new PhanSo(tu, mau);
            danhSachPhanSo.add(ps);
            sbGoc.append(String.format("%3d.  %s\n", i, ps.toString()));
        }

        // Lưu danh sách đối tượng phân số xuống tập tin fileName (.dat)
        try (FileOutputStream fos = new FileOutputStream(fileName);
             ObjectOutputStream oos = new ObjectOutputStream(fos)) {

            oos.writeObject(danhSachPhanSo);
            oos.flush();

            txtDanhSachGoc.setText(sbGoc.toString());
            txtKetQuaLoc.setText(""); // Xóa kết quả lọc cũ
            lblTrangThai.setText("Đã tạo và lưu thành công " + n + " phân số vào tập tin: " + fileName);

            JOptionPane.showMessageDialog(this,
                    "Đã tạo và lưu " + n + " phân số vào tập tin \"" + fileName + "\" thành công!",
                    "Thành công", JOptionPane.INFORMATION_MESSAGE);

        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this,
                    "Lỗi khi ghi dữ liệu xuống tập tin: " + ex.getMessage(),
                    "Lỗi", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_btnTaoVaLuuActionPerformed

    private void btnDocVaLocActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDocVaLocActionPerformed
        String fileName = txtTenFile.getText().trim();
        if (fileName.isEmpty()) {
            fileName = "phanso.dat";
            txtTenFile.setText(fileName);
        }

        File file = new File(fileName);
        if (!file.exists()) {
            JOptionPane.showMessageDialog(this,
                    "Tập tin \"" + fileName + "\" chưa tồn tại!\nVui lòng bấm 'Tạo & Lưu phân số' trước.",
                    "Tập tin không tồn tại", JOptionPane.WARNING_MESSAGE);
            return;
        }

        List<PhanSo> danhSachDocDuoc = new ArrayList<>();

        // Đọc các đối tượng phân số từ tập tin nhị phân
        try (FileInputStream fis = new FileInputStream(file);
             ObjectInputStream ois = new ObjectInputStream(fis)) {

            Object obj = ois.readObject();
            if (obj instanceof List) {
                danhSachDocDuoc = (List<PhanSo>) obj;
            } else if (obj instanceof PhanSo) {
                danhSachDocDuoc.add((PhanSo) obj);
                try {
                    while (true) {
                        danhSachDocDuoc.add((PhanSo) ois.readObject());
                    }
                } catch (EOFException eof) {
                    // Đã đọc xong toàn bộ file
                }
            }

        } catch (ClassNotFoundException ex) {
            JOptionPane.showMessageDialog(this,
                    "Không tìm thấy định dạng lớp đối tượng PhanSo: " + ex.getMessage(),
                    "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this,
                    "Lỗi khi đọc dữ liệu từ tập tin: " + ex.getMessage(),
                    "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Lọc các phân số có mẫu số là số nguyên tố
        StringBuilder sbLoc = new StringBuilder();
        sbLoc.append("=== CÁC PHÂN SỐ CÓ MẪU SỐ NGUYÊN TỐ ===\n");
        sbLoc.append(String.format("Tổng số phân số đọc từ file: %d\n", danhSachDocDuoc.size()));
        sbLoc.append("--------------------------------------\n");

        int count = 0;
        for (PhanSo ps : danhSachDocDuoc) {
            if (ps.isMauSoNguyenTo()) {
                count++;
                sbLoc.append(String.format("%2d.  %-8s (Mẫu số %d là số nguyên tố)\n",
                        count, ps.toString(), ps.getMauSo()));
            }
        }

        if (count == 0) {
            sbLoc.append("Không có phân số nào có mẫu số là số nguyên tố.\n");
        } else {
            sbLoc.append("--------------------------------------\n");
            sbLoc.append(String.format("=> Tìm thấy: %d / %d phân số thỏa mãn.", count, danhSachDocDuoc.size()));
        }

        txtKetQuaLoc.setText(sbLoc.toString());
        lblTrangThai.setText("Đã đọc " + danhSachDocDuoc.size() + " phân số từ file. Tìm thấy " + count + " phân số có mẫu số nguyên tố.");
    }//GEN-LAST:event_btnDocVaLocActionPerformed

